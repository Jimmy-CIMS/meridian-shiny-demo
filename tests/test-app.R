# Run from the repository root: Rscript tests/test-app.R
library(testthat)
library(shiny)
source('app.R')

test_that('synthetic data are reproducible and internally consistent', {
  expect_identical(make_demo_data(100),make_demo_data(100))
  expect_equal(nrow(orders),16000)
  expect_true(all(orders$cost<orders$revenue))
  expect_true(all(orders$date>=as.Date('2025-01-01') & orders$date<=as.Date('2025-12-31')))
})
test_that('filters compose and empty data remain safe',{
  d <- filter_orders(orders,c('2025-04-01','2025-06-30'),'Europe','Online store','Beauty')
  expect_gt(nrow(d),0)
  expect_true(all(d$region=='Europe' & d$channel=='Online store' & d$category=='Beauty'))
  empty <- filter_orders(orders,c('2024-01-01','2024-12-31'))
  expect_equal(summarize_orders(empty)$margin,0)
  expect_equal(summarize_orders(empty)$aov,0)
  expect_equal(nrow(customer_summary(empty)),0)
  expect_length(cohort_values(empty)$values,0)
})
test_that('scenario baseline is exact and adjustments affect demand and profit',{
  base <- scenario_projection(orders)
  expect_equal(base$revenue,sum(orders$revenue))
  expect_equal(base$profit,sum(orders$revenue-orders$cost))
  expect_equal(base$orders,nrow(orders))
  promo <- scenario_projection(orders,discount=20)
  expect_gt(promo$orders,base$orders)
  budget <- scenario_projection(orders,marketing=50)
  expect_gt(budget$marketing_spend,0)
  expect_equal(budget$profit,budget$revenue-sum(orders$cost)*1.175-budget$marketing_spend)
  expect_equal(scenario_projection(orders[FALSE,])$revenue,0)
})
test_that('cohort retention begins at 100 percent and never exceeds it',{
  c <- cohort_values(orders)
  v <- do.call(rbind,c$values)
  expect_true(all(v[,3]>=0 & v[,3]<=100))
  expect_true(all(v[v[,1]==0,3]==100))
})
test_that('server filtering, charts, search, pagination, and scenario react coherently',{
  testServer(app_server,{
    session$setInputs(dates=as.Date(c('2025-01-01','2025-12-31')),region='All regions',channel='All channels',category='All categories',metric='revenue',price=0,discount=0,marketing=0,elasticity=1.2,search='',sort='newest',ui_ready=1)
    expect_equal(nrow(filtered()),16000)
    payload <- chart_payload()
    expect_length(payload,11)
    expect_equal(sum(payload[['revenue-chart']]$series[[1]]$values),sum(orders$revenue))
    expect_match(as.character(output$overview_kpis$html),'TOTAL REVENUE')
    expect_match(as.character(output$orders_table$html),'MR-')
    session$setInputs(region='Europe',category='Beauty')
    expect_true(all(filtered()$region=='Europe'))
    expect_true(all(explored()$category=='Beauty'))
    expect_equal(sum(chart_payload()[['sales-chart']]$series[[1]]$values),sum(explored()$revenue))
    session$setInputs(search='MR-',sort='revenue')
    expect_true(all(diff(report_rows()$revenue)<=0))
    session$setInputs(next_page=1)
    expect_equal(page(),2)
    session$setInputs(search='no-such-order')
    expect_equal(nrow(report_rows()),0)
    expect_match(as.character(output$orders_table$html),'No orders found')
    session$setInputs(search='',price=10,discount=5,marketing=25)
    expect_gt(projection()$marketing_spend,0)
    session$setInputs(dates=as.Date(c('2024-01-01','2024-02-01')))
    expect_equal(nrow(filtered()),0)
    expect_equal(projection()$revenue,0)
    expect_match(as.character(output$overview_kpis$html),'\u00240',fixed=TRUE)
    expect_length(chart_payload()[['cohort-chart']]$values,0)
  })
})
